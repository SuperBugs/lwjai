/**
 * 地址（URL 里那一段）= **一个全站统一的递增数字**。
 *
 * 【2026-09-21 换掉了「标的-日期时分-智能体-模型」】旧判据在 `src/config/autoSlug.ts`，
 * 整个删了。换的理由和它当初存在的理由是同一条 —— 地址要**在创建那一刻定死**：
 *
 *   - 旧的那套是"自解释"的（`orcl-20260916-1200-spark-gemini-3-pro`），但它的自解释
 *     **只在填表顺序正确时成立**：`generate` 只拿得到标题，智能体和模型是从表单里
 *     现读的，先写标题再选下拉框就少那两段。换之前站上四条研究 / 问答里**有两条**
 *     就是这样（`qcom-20260920-0853`、`q-20260920-0443`）—— 一半的地址兑现不了承诺，
 *     而回头补标又不许改地址（改了等于把分享出去的链接打死）。
 *   - 数字没有这个问题：它不描述内容，所以内容怎么补标都不会让它变成谎话。
 *
 * ## 为什么是全站一个号池，不是每个集合各自从 1 开始
 *
 * 后台写的是**扁平文件**，`posts/foo.md` 和 `qa/foo.md` 的 id 一模一样 —— 这个仓库
 * 已经为此在两处写过"记得加集合前缀"的纪律（`src/utils/qaGroups.ts` 的折叠卡、
 * `src/utils/related.ts` 的 `sameEntry`）。一个号池之后，**id 在数据层面就是全站唯一的**，
 * 那一类"一篇研究稿和一条同名问答被折进同一张卡"的 bug 没有输入可以触发了。
 * （那两处的前缀代码**不要删**：判据不该依赖"今天的数据恰好没有重号"。）
 *
 * ## 三条容易写错的地方
 *
 *   1. **字典序不是数字序。** `["9", "10"]` 按字符串排最大的是 `"9"`，下一个就成了 `10`，
 *      而 `10` 已经有人了 —— 后台撞名会**静默**加 `-2` 后缀（keystatic.config.ts 里
 *      记着这件事），地址变成 `/posts/10-2`，而页面、构建、闸门四处全绿。所以这里按
 *      数值比，`entryNo.test.ts` 钉着这一条。
 *   2. **豁口不补。** `["1", "3"]` 的下一个是 `4`，不是 `2`。补豁口 = 把一个**已经
 *      分享出去过**的地址（第 2 条，后来删了）发给另一篇内容 —— 点进去的人看到的是
 *      一篇他没点过的稿子，而站上没有任何一处会说这件事。`content:prune` 按时间段删
 *      老稿，豁口是这个站的常态，不是异常。
 *   3. **认不出的 id 一律忽略，不抛。** 这个函数跑在后台的表单里（浏览器），抛一次
 *      就是一格填不出来的地址。"盘上有个不是号的文件名"这件事由
 *      `src/content.config.ts` 的 `generateId` 去红 —— 那一处在 `pnpm dev` 里就炸，
 *      而且指得出是哪个文件。两件事，两个落点，别让这一个替那一个背书。
 *
 * 零 import：`scripts/content/importPlan.ts` 和它的测试是裸 tsx 跑的
 * （没有 `@/` 别名、没有 astro 虚拟模块），`keystatic.config.ts` 则跑在浏览器里。
 */

/**
 * 号**从 1000 起**。【2026-09-21】
 *
 * 表面理由是好看（全站号宽一致，不会一眼看出"这站统共才七条"）。
 * ★ 真正值钱的是它**结构性地消掉了一次撞车**：列表页的分页也是数字地址 ——
 *   `/r`、`/r/2`、`/r/3`…（`[...page].astro` 的 `paginate`）。条目号要是从 1 起，
 *   第 2 篇研究稿的地址 `/r/2` 和"研究稿列表第 2 页"**是同一个地址**，
 *   谁先生成谁赢，而两边都不报错。号从 1000 起、且下面那条正则**要求至少四位**之后，
 *   分页要撞上它得先有 1000 页 —— 这件事不再取决于"今天恰好内容少"。
 * ⚠ 所以 `ENTRY_NO_MIN` 和 `ENTRY_NO_RE` 的位数是**一对**，改一个要改另一个。
 */
export const ENTRY_NO_MIN = 1000;

/**
 * 一个合法的条目号：十进制、**至少四位**、不许前导零。
 *
 * ★ 不许前导零不是洁癖：`1007` 和 `01007` 是**两个地址**，却是同一个号 —— 两条内容
 *   可以各占一个，而站上、后台、闸门都看不出哪里不对。YAML 还会把裸 `01007` 读成
 *   别的东西（`questionKey` / `prompt` 那两格引用的就是这个号）。
 * ★ 至少四位是上面那条"不和分页撞车"的落点，不是排版偏好。
 */
export const ENTRY_NO_RE = /^[1-9][0-9]{3,}$/;

/** 这个 id 是不是一个条目号。`1007` 是，`7`、`7-2`（后台撞名加的后缀）、`01007` 都不是。 */
export function isEntryNo(id: string): boolean {
  return ENTRY_NO_RE.test(id);
}

/**
 * 下一个号 —— 现有的最大号 + 1，空站从 `1` 开始。
 *
 * `ids` 是**全站所有编号集合**的 id（研究稿 / 问答 / 教程 / 提示词一起），
 * 调用方各自去取：
 *   - `scripts/content/import.ts`、`src/dev/import-run.ts`、`src/dev/next-no.ts` —— 读盘；
 *   - `keystatic.config.ts` —— Vite 的 `import.meta.glob`（浏览器里没有 fs）。
 */
export function nextEntryNo(ids: Iterable<string>): string {
  // 空站从 ENTRY_NO_MIN 起（不是 1 —— 理由在那个常量上面）。
  let max = ENTRY_NO_MIN - 1;
  for (const id of ids) {
    // 按数值比，不是按字符串比（见文件头第 1 条）。
    if (isEntryNo(id)) max = Math.max(max, Number(id));
  }
  return String(max + 1);
}

/**
 * 文件名（`7.md`）里的那一段 id。
 *
 * 和 `src/utils/getPostPaths.ts` 的 `getIdSlug` 一样只取最后一段：这几个集合都是扁平的，
 * 但 glob 的 `entry` 在别的形状下可能带子目录。
 */
export function idFromEntryPath(entry: string): string {
  const file = entry.replaceAll("\\", "/").split("/").pop() ?? entry;
  return file.replace(/\.(md|mdx)$/i, "");
}
