/**
 * 发布闸的规则表。
 *
 * ★ **这张表是唯一的一份。** 两个地方都读它：
 *     ① `pnpm gate` / `pnpm gate:staged`（pre-commit）—— 提交之前
 *     ② `pnpm build` 的第一步 —— 命中就构建失败，站上留旧版本
 *   复制一份出去改，就是两道闸开始各说各话的那一天。
 *
 *   ⚠【2026-09-18 查实，这里以前写着一句假话】原文写的是"三个地方"，第一条是
 *   「Keystatic 后台的字段校验 —— 你粘贴的那一刻就报」。**后台从来没调过 `scan()`**，
 *   它一个字都不校验。那句话让人以为粘贴时就有一道防线，而实际上第一道防线是
 *   pre-commit。同日删掉的豁免机制曾经是第三个读者（后台的豁免下拉框）。
 *
 * ## 为什么需要它
 *
 * 红线是「持仓 / 成本 / 数量 / 方向 / 凭证，一个字节都不许上站」。站是公网明面，
 * 而写研究的人自己在交易 —— 研究是在装着自己仓位的上下文里跑出来的。
 *
 * 而且这一层的载荷是**人和模型写的自由文本**。结构化的数据能靠"schema 里根本没有这个字段"来挡，
 * 自由文本挡不住 —— 你让 Gemini 研究 TSLA，它顺手写一句"结合你当前 200 股的底仓"，
 * 这句话就躺在正文里了。
 *
 * ## 判定是三档，不是"通过 / 不通过"
 *
 *   - `clean` —— 扫完了，没命中。
 *   - `warn`  —— 命中的是**意图**（"我打算买"）。能发，但你要知道自己写了这句。
 *   - `block` —— 命中的是**事实**（"我持有"、"我的成本"）。**发不出去，没有放行口** ——
 *     唯一的出路是改文案（2026-09-18 删掉了豁免机制）。
 *
 * ★ **`clean` 说的是"这份稿子里没有我认识的危险说法"，不是"这份稿子安全"。**
 *   词表必然漏 —— 中文表达一句话有二十种写法。所以界面上那句话写的是「没命中已知说法」，
 *   不是「已通过安全检查」。把"我没发现"说成"没有问题"，是这个项目最不能接受的错误。
 *
 * ## 误伤是必然的，所以命中必须**摆出上下文**
 *
 * 「机构持仓占比 62%」「持仓量创新高」是正常的行情用语，词表一定会咬到它们。
 * 只报一句"不通过"等于让人删掉正确的句子。所以每一条命中都带**原文片段 + 前后文 +
 * 这条规则为什么存在**，让人自己判"这个'持仓'说的是我还是别人"。
 *
 * ★ 高危规则**一律带第一人称锚点**（`我` / `自己` / `账户`），就是为了把误伤压下去 ——
 *   裸的「持仓」「成本」「加仓」只进 warn 档。
 */

export type Level = "block" | "warn";
export type Verdict = "clean" | "warn" | "block";

export interface Rule {
  /** 稳定标识。命中时原样印在屏幕上，两个测试文件也按它断言 ——
   *  所以改 pattern 可以，改 code 要同时改测试。 */
  code: string;
  level: Level;
  pattern: RegExp;
  /** 给人看的一句话：这条为什么存在。命中时原样摆在屏幕上 ——
   *  一条看不懂为什么的规则，人只会闭着眼睛把它降成 warn。 */
  why: string;
}

/**
 * 第一人称锚点。高危规则全部围绕它构造。
 *
 * `我` 后面允许夹几个字（"我这边的成本"、"我现在持有"），但有两条硬边界：
 *
 * 1. **不许跨句**：中文句号 / 问号 / 感叹号 / 分号 / 换行。否则
 *    "别人怎么想我不知道。机构持仓 62%" 会被连成一条命中。
 *
 * 2. **不许跨过「建议」**（2026-09-18 加）。原来的锚点允许夹 6 个字，于是
 *    「我建议先别建仓」「我建议你先开仓一小笔」「我不建议长期持有大额现金」
 *    「我们建议加仓前先把出金链路跑通一次」「关于我建议的仓位大小」
 *    全部被判成 block —— 而这些是**建议语气**，不是在陈述自己的仓位。
 *    教程类文章通篇是这个语气，不修的话那一整个题材一个字都发不出去。
 *    写法是 tempered token：夹缝里的每一个字都要先确认自己不是「建议」的开头。
 */
const I = String.raw`我(?:们)?(?:(?!建议)[^。！？；\n]){0,6}?`;

const r = (code: string, level: Level, pattern: string, why: string): Rule => ({
  code,
  level,
  // `g` 是 matchAll 的硬要求；`u` 让中文与代理对字符按码点算长度。
  pattern: new RegExp(pattern, "gu"),
  why,
});

