/**
 * 发布闸的测试。
 *
 * ★ **用例一律从"模型真的会这么写"来，不许照着正则反推。**
 *
 * 作者的另一个项目出过一次最贵的 bug 就是这个形态：`FORMS` 里写的是 `SC 13D`，而 SEC 现网给的是
 * `SCHEDULE 13D`，**87 条测试全绿，因为测试自己喂的也是 `SC 13D`** —— 断言和代码一起错，
 * 而且零症状（界面写「登记 0 份」，`ok=1`，告警零条，库里 109 行就摆在那儿）。
 *
 * 所以下面每一条 block 用例的原文，都是一句**完整的、Gemini 研究稿里真会出现的中文**，
 * 不是 `我持有` 这种从 pattern 里抠出来的碎片。
 *
 * ⚠ 例句里的数字（成本 187、300 股、浮盈 15% 这些）**全是编的**，不是任何人的真实仓位 ——
 *   它们只负责长得像模型真会写出来的句子。
 *
 * 跑：`pnpm test`
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import { scan } from "./scan";
import { RULES } from "./rules";

// ── 真会泄露的句子：必须 block ──────────────────────────────────────────

const MUST_BLOCK: [string, string, string][] = [
  [
    "own_position",
    "结合你当前的底仓情况，我持有的这部分在财报后可以继续拿着观察一个季度。",
    "模型顺着上下文把'你的底仓'写成了'我持有'",
  ],
  [
    "own_trade",
    "上周回调到 210 附近的时候我加仓了一些，现在看这个位置的支撑是有效的。",
    "复盘口吻里最常见的一句",
  ],
  [
    "own_cost",
    "考虑到我的成本在 187 左右，当前价格对应的浮盈大约是 15%。",
    "成本价，红线 4 点名的四项之一",
  ],
  [
    "own_size",
    "这只票在我的仓位里占比不到 5%，所以即使判断错了影响也有限。",
    "规模，红线 4 点名的四项之一",
  ],
  [
    "position_size_number",
    "目前我手上还有 300 股，打算等财报落地之后再决定要不要动。",
    "最直接的股数泄露",
  ],
  [
    // 2026-09-18：原来这条用的是「这笔交易在嘉信上的手续费是 0」（裸券商名）。
    // 站里开始写开户教程之后裸名字那一半撤了（见 rules.ts 里 own_broker 那段），
    // 换成真正的红线形态：**第一人称 + 在哪家开的户**。
    "own_broker",
    "我在嘉信开的户，转账免费，这点比别家强。",
    "说出自己在哪家开户",
  ],
  [
    "own_broker",
    "我券商那边的融资利率最近涨了一档。",
    "第一人称 + 券商，不带具体名字也一样是红线",
  ],
  [
    "credential",
    "调用的时候记得把 api_key 换成你自己的：AIzaSyB1234567890abcdefghijklmnop",
    "凭证，最贵的一项",
  ],
  [
    "internal_system",
    "这份数据是从 example_server 的情报库里取的，private.db 里存了近一年的申报。",
    "把私有系统的结构图挂在门口",
  ],
];

for (const [expectedCode, text, note] of MUST_BLOCK) {
  test(`block: ${expectedCode} —— ${note}`, () => {
    const r = scan(text);
    assert.equal(r.verdict, "block", `这句应该被拦下来：${text}`);
    assert.ok(
      r.blocking.some(h => h.code === expectedCode),
      `应该命中 ${expectedCode}，实际命中：${r.hits.map(h => h.code).join(",") || "（无）"}`
    );
    // 命中必须带上下文 —— 只报"不通过"等于让人删掉正确的句子。
    const hit = r.blocking.find(h => h.code === expectedCode)!;
    assert.ok(hit.context.length > hit.matched.length, "命中要摆出前后文");
    assert.ok(hit.rule.why.length > 10, "每条规则都要能说出自己为什么存在");
  });
}

// ── 误伤：正常行情用语，**不许** block ──────────────────────────────────
// 这一组比上面那组更重要。闸门如果天天咬正确的句子，人就会养成闭眼豁免的习惯，
// 到那时它已经废了 —— 只是没人知道而已。

