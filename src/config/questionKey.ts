/**
 * 问答的「问题组」键 —— 同一个问题问了几个智能体时，把那几条归成一组用的钥匙。
 *
 * ## 为什么是封闭格式，不是自由文本
 *
 * 这个键**上公网**（进 frontmatter、进导出对账），而发布闸不扫它。
 * 闸门的规矩（docs/gate.md 第 4 节）：会上公网的自由文本要么扫、要么封闭。
 * 所以它只许是小写 ASCII slug —— 和文件名（URL 里那一段）同一类东西：
 * 人手填、纯 ASCII、装不下一句中文。
 *
 * ## 为什么按键分组，不按标题分组
 *
 * 「同一个问题」在标题上未必逐字相同（问模型的时候顺手改了两个字），
 * 而按标题分组的失败是静默的：两条本该并排的回答各自孤零零。
 * 显式的键至少让"这两条是一组"成为一个人写下来的事实。
 * ⚠ 键打错一个字母同样静默 —— 所以详情页在「有键但没有别的回答」时
 *   会印一句「这个问题目前只有这一条回答」，而不是什么都不显示（docs/engineering-notes.md 第二节：
 *   「没填键」和「填了键但没对上」是两档，不许长得一样）。
 *
 * ★ 这个文件**一个 import 都不许有**：`keystatic.config.ts` 在 Astro 之外加载，
 *   碰不到 `astro:content` 和 `@/` 别名（理由同 `promptOrigins.ts`）。
 */

/** 小写字母 / 数字，连字符分段；不许以连字符开头或结尾，不许连续两个连字符。 */
export const QUESTION_KEY_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/**
 * schema 报错时给人看的那句提示。
 *
 * 【2026-09-20】后台那一格**不再是文本框**，是从已有问题里挑的下拉
 * （`keystatic.config.ts` 的 `questionOptions()`），所以这句话现在只有构建期用得上 ——
 * 落到它，说明有人绕过后台手写了 frontmatter。
 */
export const QUESTION_KEY_HINT =
  "只许小写字母、数字和连字符，如 tsla-gross-margin；只问过一次就留空";
